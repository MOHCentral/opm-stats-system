def generate_go_normalization(aliases):
    """Generate Go normalization function."""
    timestamp = datetime.now().isoformat()
    
    lines = [
        '// Code generated by tools/generate_types.py. DO NOT EDIT.',
        f'// Generated at: {timestamp}',
        '// Source: opm-stats-api/web/static/openapi.yaml',
        '',
        'package handlers',
        '',
        'import "github.com/openmohaa/stats-api/internal/models"',
        '',
        '// normalizeEventType maps game script event types to canonical API types.',
        '// This ensures consistent event_type values in ClickHouse for querying.',
        '// GENERATED - edit openapi.yaml and run `make generate-types`',
        'func normalizeEventType(eventType models.EventType) models.EventType {',
        '\tswitch eventType {',
    ]
    
    for alias, canonical in sorted(aliases.items()):
        canonical_const = to_go_const_name(canonical)
        lines.append(f'\tcase "{alias}":')
        lines.append(f'\t\treturn models.{canonical_const}')
    
    lines.append('\tdefault:')
    lines.append('\t\treturn eventType')
    lines.append('\t}')
    lines.append('}')
    lines.append('')
    
    return '\n'.join(lines)


def to_php_const_name(event_type):
    """Convert event type to PHP constant name (e.g., 'player_kill' -> 'PLAYER_KILL')."""
    return event_type.upper()


def generate_php_class(event_types, aliases):
    """Generate PHP EventTypes class."""
    timestamp = datetime.now().isoformat()
    
    lines = [
        '<?php',
        'declare(strict_types=1);',
        '',
        '/**',
        ' * Event Type Constants',
        ' * ',
        ' * GENERATED FILE - DO NOT EDIT DIRECTLY',
        f' * Generated at: {timestamp}',
        ' * Source: opm-stats-api/web/static/openapi.yaml',
        ' * ',
        ' * To add new event types, edit openapi.yaml and run `make generate-types`',
        ' */',
        '',
        'namespace MohaaSMF;',
        '',
        '/**',
        ' * Canonical event type constants for the OpenMOHAA Stats system.',
        ' * Use these constants instead of string literals to ensure type safety.',
        ' */',
        'class EventTypes',
        '{',
    ]
    
    for event_type in event_types:
        const_name = to_php_const_name(event_type)
        lines.append(f"    public const {const_name} = '{event_type}';")
    
    lines.append('')
    lines.append('    /**')
    lines.append('     * Map of aliases to canonical event types.')
    lines.append('     * Use this for display or when receiving data from external sources.')
    lines.append('     */')
    lines.append('    public const ALIASES = [')
    
    for alias, canonical in sorted(aliases.items()):
        lines.append(f"        '{alias}' => self::{to_php_const_name(canonical)},")
    
    lines.append('    ];')
    lines.append('')
    lines.append('    /**')
    lines.append('     * Normalize an event type to its canonical form.')
    lines.append('     */')
    lines.append('    public static function normalize(string $eventType): string')
    lines.append('    {')
    lines.append('        return self::ALIASES[$eventType] ?? $eventType;')
    lines.append('    }')
    lines.append('')
    lines.append('    /**')
    lines.append('     * Check if an event type is valid (canonical or alias).')
    lines.append('     */')
    lines.append('    public static function isValid(string $eventType): bool')
    lines.append('    {')
    lines.append('        static $all = null;')
    lines.append('        if ($all === null) {')
    lines.append('            $reflection = new \\ReflectionClass(self::class);')
    lines.append('            $constants = $reflection->getConstants();')
    lines.append('            $all = array_flip(array_filter($constants, fn($v) => is_string($v) && $v !== \'\'));')
    lines.append('        }')
    lines.append('        return isset($all[$eventType]) || isset(self::ALIASES[$eventType]);')
    lines.append('    }')
    lines.append('}')
    lines.append('')
    
    return '\n'.join(lines)


