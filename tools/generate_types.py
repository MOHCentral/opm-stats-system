def load_openapi():
    """Load and parse the OpenAPI spec."""
    with open(OPENAPI_PATH, 'r') as f:
        return yaml.safe_load(f)


def extract_event_types(spec):
    """Extract event types and aliases from OpenAPI spec."""
    schemas = spec.get('components', {}).get('schemas', {})
    
    # Get main enum
    event_type_schema = schemas.get('EventType', {})
    event_types = event_type_schema.get('enum', [])
    
    # Get aliases
    alias_schema = schemas.get('EventTypeAlias', {}).get('properties', {})
    aliases = {}
    for alias, mapping in alias_schema.items():
        canonical = mapping.get('const', '')
        if canonical:
            aliases[alias] = canonical
    
    return event_types, aliases


def to_go_const_name(event_type):
    """Convert event type to Go constant name (e.g., 'player_kill' -> 'EventPlayerKill')."""
    parts = event_type.split('_')
    return 'Event' + ''.join(p.capitalize() for p in parts)


